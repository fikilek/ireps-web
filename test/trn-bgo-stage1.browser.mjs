import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { OFFICIAL_HEADERS } from "../functions/tcUploads/stage1Validation.js";
// Point PLAYWRIGHT_PACKAGE at an installed playwright index.mjs when not installed in this repo.
const { chromium } = await import(process.env.PLAYWRIGHT_PACKAGE ? pathToFileURL(process.env.PLAYWRIGHT_PACKAGE).href : "playwright");
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on("pageerror", (error) => errors.push(error.message));
const file = (meters) => Buffer.from([OFFICIAL_HEADERS.join(","), ...meters.map((meter, index) => [index + 1, meter, "Single Phase", "electricity", "00045", "12 Test Road", "Residential", "Review", "6", "Fence", "CONNECTED", "0123"].join(","))].join("\r\n"));
const open = () => page.goto("http://127.0.0.1:5196/test/stage1-ui/index.html");
try {
  await open();
  await page.getByRole("heading", { name: "TRN BGO File Upload" }).waitFor();
  assert.equal(await page.getByLabel("TRN Type", { exact: true }).locator("option").count(), 7);
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Sample Template" }).click();
  assert.equal((await downloadPromise).suggestedFilename(), "TRN_BGO_Sample_Template.xlsx");
  await page.locator('input[type="file"]').setInputFiles({ name: "Original Name.csv", mimeType: "text/csv", buffer: file(["0001", "0002", "0001", "0002", "009999"]) });
  const dialog = page.getByRole("dialog", { name: "Resolve duplicate meter numbers" });
  await dialog.waitFor();
  assert.equal(await dialog.locator("tbody tr").count(), 4);
  assert.equal(await dialog.locator("thead th").count(), 26, "each duplicate group has keep/drop plus all 12 columns");
  assert.equal(await dialog.locator('input[type="radio"]:checked').count(), 0);
  assert.equal(await dialog.getByRole("button", { name: "Continue" }).isDisabled(), true);
  await dialog.locator('input[name="keep-0001"]').nth(1).check();
  assert.equal(await dialog.getByRole("button", { name: "Continue" }).isDisabled(), true);
  await dialog.locator('input[name="keep-0002"]').nth(0).check();
  assert.equal(await dialog.getByText("DROP", { exact: true }).count(), 2);
  await dialog.getByRole("button", { name: "Continue" }).click();
  await dialog.waitFor({ state: "detached" });
  await page.getByText("Original Name.csv", { exact: true }).waitFor();
  const payload = await page.evaluate(() => window.__stage1Payload);
  assert.equal(payload.rows.length, 5); assert.deepEqual(payload.keep, { "0001": "3", "0002": "2" });
  assert.equal(payload.lmPcode, "ZA5241"); assert.equal(payload.trnType, "METER_DISCONNECTION");
  assert.ok(await page.getByRole("columnheader", { name: "Found?", exact: true }).count());
  assert.ok(await page.getByRole("columnheader", { name: "dataMatch", exact: true }).count());
  assert.equal(await page.locator("tbody tr").count(), 3, "report receives only resolved working rows");
  if (process.env.STAGE1_SCREENSHOT) await page.screenshot({ path: process.env.STAGE1_SCREENSHOT, fullPage: true });
  await open();
  await page.locator('input[type="file"]').setInputFiles({ name: "too-many.csv", mimeType: "text/csv", buffer: file(Array.from({ length: 201 }, (_, i) => `00${i}`)) });
  const failure = page.getByRole("dialog", { name: "Upload validation failed" }); await failure.waitFor();
  assert.match(await failure.innerText(), /201.*200.*Split/s);
  await open();
  await page.getByLabel("TRN Type", { exact: true }).selectOption("METER_COMMISSIONING");
  await page.locator('input[type="file"]').setInputFiles({ name: "not-found.csv", mimeType: "text/csv", buffer: file(["009999"]) });
  await page.getByText("not-found.csv", { exact: true }).waitFor();
  assert.equal((await page.evaluate(() => window.__stage1Payload)).trnType, "METER_COMMISSIONING");
  assert.equal(await page.locator("tbody tr").count(), 1);
  await open();
  await page.locator('input[type="file"]').setInputFiles({ name: "wrong-lm.csv", mimeType: "text/csv", buffer: file(["000456"]) });
  const mismatch = page.getByRole("dialog", { name: "Municipality mismatch" }); await mismatch.waitFor();
  assert.equal(await mismatch.locator("thead th").count(), 13);
  assert.match(await mismatch.innerText(), /000456/); assert.match(await mismatch.innerText(), /ZA9999/);
  await mismatch.getByRole("button", { name: "OK" }).click();
  assert.equal(await page.locator("tbody tr").count(), 1);
  assert.deepEqual(errors, []);
  console.log("Stage 1 browser checks passed: template, seven types, all duplicate groups/full rows, explicit keep/drop gate, original filename/context, report handoff, 201-row modal, all-NOT-FOUND commissioning.");
} catch (error) { console.error("Browser errors:", errors); console.error((await page.locator("body").innerText()).slice(0, 2000)); throw error; } finally { await browser.close(); }
